// Dependency updates: a weekly check (or one on the repository's schedule
// day, and "Check now") finds manifests anywhere on the default branch —
// go.mod, package.json (and npm/pnpm/yarn workspaces), Gradle build scripts,
// version catalogs and the wrapper — asks the Go proxy, the npm registry,
// Maven Central, Google Maven, the Gradle Plugin Portal and
// services.gradle.org for newer versions and OSV for known
// vulnerabilities, and, when the repository allows it, opens update pull
// requests authored by the atelier-updates bot: one per dependency, or one
// per manager and folder for minor and patch updates when grouping is on.
// Only manifests are edited here; lockfiles are regenerated by an Actions
// job (security_deps_lockfiles.go), never by the server.

const (
	settingSecGoProxy     = "security.goproxy"      // GOPROXY-style list for update checks
	settingSecNpmRegistry = "security.npm_registry" // npm registry when Atelier's upstream cache is off
	defaultSecGoProxy     = "https://proxy.golang.org"
	defaultSecNpmRegistry = "https://registry.npmjs.org"

	secBotName   = "atelier-updates"
	secBotBranch = depupdates.BranchRoot
)

var (
	secOSVURL          = depupdates.DefaultOSVURL
	secMavenCentralURL = depupdates.DefaultMavenCentralURL
	secGoogleMavenURL  = depupdates.DefaultGoogleMavenURL
	secPluginPortalURL = depupdates.DefaultPluginPortalURL
	secGradleURL       = depupdates.DefaultGradleURL
	secHTTPClient      = &http.Client{Timeout: 20 * time.Second}
	secDepsEvery       = 7 * 24 * time.Hour
	secDepsTimeout     = 5 * time.Minute
	secBot             = Actor{Kind: "bot", Name: secBotName}
	secMaxTreeEntries  = 200000
)

func (a *App) secGoProxySetting(ctx context.Context) string {
	if v := strings.TrimSpace(os.Getenv("ATELIER_GOPROXY")); v != "" {
		return v
	}
	if v, err := a.db.Setting(ctx, settingSecGoProxy); err == nil && v != "" {
		return v
	}
	return defaultSecGoProxy
}

func (a *App) secNpmRegistrySetting(ctx context.Context) string {
	if v, err := a.db.Setting(ctx, settingSecNpmRegistry); err == nil && v != "" {
		return v
	}
	return defaultSecNpmRegistry
}

func (a *App) secSaveRegistries(ctx context.Context, goproxy, npm string) error {
	goproxy = strings.TrimSpace(goproxy)
	if len(depupdates.ParseGoProxy(goproxy)) == 0 {
		goproxy = ""
	}
	npm = strings.TrimRight(strings.TrimSpace(npm), "/")
	if u, err := url.Parse(npm); err != nil || (u.Scheme != "https" && u.Scheme != "http") || u.Host == "" {
		npm = ""
	}
	return errors.Join(a.db.SetSetting(ctx, settingSecGoProxy, goproxy), a.db.SetSetting(ctx, settingSecNpmRegistry, npm))
}

// secHost is the host name this Atelier serves Go modules under.
func (a *App) secHost(ctx context.Context) string {
	base := a.cfg.PublicURL
	if base == "" {
		base, _ = a.db.Setting(ctx, settingSecurityBaseURL)
	}
	if u, err := url.Parse(base); err == nil {
		return strings.ToLower(u.Host)
	}
	return ""
}

// secChecker builds the version and advisory sources: Atelier's own Go proxy
// and npm registry first, then the configured public ones.
func (a *App) secChecker(ctx context.Context) depupdates.Checker {
	host := a.secHost(ctx)
	owner, _ := a.db.PersonalOwner(ctx)
	reader := personActor(owner)
	goLocal := func(ctx context.Context, mod string) ([]string, bool) {
		if host == "" || !strings.HasPrefix(strings.ToLower(mod), host+"/") {
			return nil, false
		}
		m, ok := a.goResolve(ctx, reader, mod)
		if !ok {
			return nil, false
		}
		return a.goVersions(ctx, m), true
	}
	upstream, viaAtelier := a.npmUpstream(ctx)
	npmDoc := func(ctx context.Context, name string) ([]byte, bool, error) {
		if scope, bare := npmScope(name); scope != "" {
			if o, err := a.db.OwnerByName(ctx, scope); err == nil {
				// One of Atelier's own scopes: never ask a public registry.
				p, err := a.db.Package(ctx, o.ID, store.PkgNpm, bare)
				if err != nil {
					return nil, false, fmt.Errorf("%s isn't in Atelier's npm registry", name)
				}
				vers, err := a.db.Versions(ctx, p.ID)
				if err != nil {
					return nil, false, err
				}
				var b strings.Builder
				b.WriteString(`{"versions":{`)
				for i, v := range vers {
					if i > 0 {
						b.WriteString(",")
					}
					fmt.Fprintf(&b, "%q:{}", v.Version)
				}
				b.WriteString("}}")
				return []byte(b.String()), true, nil
			}
		}
		if viaAtelier {
			body, err := a.npmUpstreamDoc(ctx, upstream, name)
			return body, err == nil, err
		}
		return nil, false, nil
	}
	return depupdates.Checker{
		Go:  depupdates.GoProxy{URLs: depupdates.ParseGoProxy(a.secGoProxySetting(ctx)), Client: secHTTPClient, Local: goLocal},
		Npm: depupdates.NpmRegistry{URL: a.secNpmRegistrySetting(ctx), Client: secHTTPClient, Doc: npmDoc},
		Maven: depupdates.MavenRepos{Central: secEnvURL("ATELIER_MAVEN_CENTRAL", secMavenCentralURL),
			Google: secEnvURL("ATELIER_GOOGLE_MAVEN", secGoogleMavenURL), PluginPortal: secEnvURL("ATELIER_GRADLE_PLUGIN_PORTAL", secPluginPortalURL),
			Client: secHTTPClient},
		Gradle: depupdates.GradleReleases{URL: secEnvURL("ATELIER_GRADLE_SERVICES", secGradleURL), Client: secHTTPClient},
		OSV:    &depupdates.OSV{URL: secEnvURL("ATELIER_OSV_URL", secOSVURL), Client: secHTTPClient},
	}
}

// secEnvURL lets an environment variable replace a registry (a mirror, or
// an offline test server): ATELIER_MAVEN_CENTRAL, ATELIER_GOOGLE_MAVEN,
// ATELIER_GRADLE_PLUGIN_PORTAL, ATELIER_GRADLE_SERVICES, ATELIER_OSV_URL.
func secEnvURL(env, def string) string {
	v := strings.TrimRight(strings.TrimSpace(os.Getenv(env)), "/")
	if u, err := url.Parse(v); v != "" && err == nil && (u.Scheme == "https" || u.Scheme == "http") && u.Host != "" {
		return v
	}
	return def
}

// secStartDepsCheck starts a background check; done names the page flash.
func (a *App) secStartDepsCheck(ctx context.Context, repo store.Repo) (string, error) {
	if !a.secHasManifest(ctx, repo) {
		return "nodeps", nil
	}
	ok, err := a.db.StartSecurityScan(ctx, repo.ID, "deps", secDepsTimeout+time.Minute)
	if err != nil {
		return "", err
	}
	if !ok {
		return "checking", nil
	}
	ctx = context.WithoutCancel(ctx)
	secGo(func() { a.secFinishDepsCheck(ctx, repo) })
	return "deps", nil
}

func (a *App) secFinishDepsCheck(ctx context.Context, repo store.Repo) {
	ctx, cancel := context.WithTimeout(ctx, secDepsTimeout)
	defer cancel()
	sc := store.SecurityScan{RepoID: repo.ID, Kind: "deps"}
	if err := a.secCheckDeps(ctx, repo); err != nil {
		sc.Error = err.Error()
	}
	if err := a.db.FinishSecurityScan(context.WithoutCancel(ctx), sc); err != nil {
		log.Printf("security: dependency check of %s: %v", repo.FullName(), err)
	}
}

// secTreeFiles lists every file path at a commit.
func secTreeFiles(ctx context.Context, g *gitrepo.Repo, sha string) ([]string, error) {
	var files []string
	err := g.StreamGit(ctx, time.Minute, func(r io.Reader) error {
		b, err := io.ReadAll(io.LimitReader(r, 64<<20))
		if err != nil {
			return err
		}
		for _, p := range strings.Split(string(b), "\x00") {
			if p != "" {
				files = append(files, p)
			}
			if len(files) >= secMaxTreeEntries {
				break
			}
		}
		return nil
	}, "-c", "core.quotePath=false", "ls-tree", "-r", "-z", "--name-only", "--full-tree", sha)
	return files, err
}

// secManifests finds the default branch's manifests.
func (a *App) secManifests(ctx context.Context, g *gitrepo.Repo, tip string) ([]depupdates.Manifest, []string, error) {
	files, err := secTreeFiles(ctx, g, tip)
	if err != nil {
		return nil, nil, err
	}
	return depupdates.Discover(files), files, nil
}

func (a *App) secHasManifest(ctx context.Context, repo store.Repo) bool {
	g, err := a.git.Open(repo.Owner, repo.Name)
	if err != nil || g.IsEmpty(ctx) {
		return false
	}
	tip, err := g.BranchSHA(ctx, g.DefaultBranch(ctx))
	if err != nil {
		return false
	}
	ms, _, err := a.secManifests(ctx, g, tip)
	return err == nil && len(ms) > 0
}

// secReadDeps reads every manifest: its dependencies, minus packages the
// repository builds itself (workspace siblings, its own Go modules). npm
// workspace members are grouped under their workspace root, where the
// lockfile lives.
func secReadDeps(ctx context.Context, g *gitrepo.Repo, tip string, ms []depupdates.Manifest, files []string) ([]depupdates.Dep, []string) {
	have := map[string]bool{}
	for _, f := range files {
		have[f] = true
	}
	var problems []string
	var local depupdates.Local
	data := map[string][]byte{}
	wsRoots := map[string][]string{}
	for _, m := range ms {
		b, err := g.Blob(ctx, tip, m.Path, 1<<20)
		if err != nil || b.TooLarge || b.Binary {
			problems = append(problems, m.Path+" couldn't be read")
			continue
		}
		data[m.Path] = b.Data
		local.AddManifest(m, b.Data)
		if m.Kind == "npm" {
			var pnpm []byte
			if p := path.Join(m.Root, "pnpm-workspace.yaml"); have[strings.TrimPrefix(p, "/")] {
				if pb, err := g.Blob(ctx, tip, strings.TrimPrefix(p, "/"), 1<<16); err == nil && !pb.TooLarge {
					pnpm = pb.Data
				}
			}
			if globs := depupdates.Workspaces(b.Data, pnpm); len(globs) > 0 {
				wsRoots[m.Root] = globs
			}
		}
	}
	var deps []depupdates.Dep
	for _, m := range ms {
		b, ok := data[m.Path]
		if !ok {
			continue
		}
		ds, err := depupdates.ParseManifest(m, b)
		if err != nil {
			problems = append(problems, m.Path+" couldn't be read: "+err.Error())
			continue
		}
		root := m.Root
		if m.Kind == "npm" {
			if r, ok := depupdates.WorkspaceRoot(m.Root, wsRoots); ok {
				root = r
			}
		}
		for _, d := range ds {
			if local.Has(d) {
				continue
			}
			d.Root = root
			deps = append(deps, d)
		}
	}
	return deps, problems
}

// secCheckDeps checks the default branch's manifests, stores the results and
// opens update pull requests as the repository's settings allow.
func (a *App) secCheckDeps(ctx context.Context, repo store.Repo) error {
	g, err := a.git.Open(repo.Owner, repo.Name)
	if err != nil {
		return err
	}
	if g.IsEmpty(ctx) {
		return a.db.ReplaceDepUpdates(ctx, repo.ID, nil)
	}
	base := g.DefaultBranch(ctx)
	if depupdates.IsUpdateBranch(base) {
		// HEAD names a branch that doesn't exist and git fell back to the newest
		// branch, which is one of ours: never base updates on an update branch.
		return fmt.Errorf("the default branch couldn't be found (HEAD points at a missing branch, newest is %s); set it in the repository settings", base)
	}
	tip, err := g.BranchSHA(ctx, base)
	if err != nil {
		return err
	}
	ms, files, err := a.secManifests(ctx, g, tip)
	if err != nil {
		return err
	}
	deps, problems := secReadDeps(ctx, g, tip, ms, files)
	results, err := a.secChecker(ctx).Check(ctx, deps)
	if err != nil {
		problems = append(problems, err.Error())
	}
	settings, err := a.db.SecuritySettings(ctx, repo.ID)
	if err != nil {
		return err
	}
	dset, err := a.db.DepUpdateSettings(ctx, repo.ID)
	if err != nil {
		return err
	}
	bot, err := a.secBotPRs(ctx, repo.ID)
	if err != nil {
		return err
	}

	failed := 0
	for _, r := range results {
		if r.Err != nil {
			failed++
		}
	}
	plans := depupdates.Plan(results, depupdates.PlanOptions{
		Group:  dset.GroupMinor,
		Wanted: func(r depupdates.Result) bool { return settings.AllPRs || settings.SecurityPRs && len(r.Vulns) > 0 },
		Skip:   func(r depupdates.Result) bool { return bot.openFor(r.Dep) != nil },
	})
	opened := map[string]int64{} // manifest \x00 name -> PR number
	for _, p := range plans {
		n, err := a.secOpenPlannedPR(ctx, repo, g, base, tip, p, bot, dset)
		if err != nil {
			problems = append(problems, fmt.Sprintf("pull request for %s: %v", secPlanName(p), err))
		}
		if n == 0 {
			continue
		}
		for _, r := range p.Updates {
			opened[r.Manifest+"\x00"+r.Name] = n
		}
	}

	var ups []store.DepUpdate
	for _, r := range results {
		if r.Err != nil || r.Latest == "" && len(r.Vulns) == 0 {
			continue
		}
		u := store.DepUpdate{RepoID: repo.ID, Ecosystem: r.Ecosystem, Name: r.Name, Manifest: r.Manifest, Current: r.Spec,
			Kind: r.Kind, Vulns: len(r.Vulns), VulnIDs: strings.Join(r.Vulns, ","), Fixes: r.Fixes}
		if r.Latest != "" {
			u.Latest, u.NewSpec = r.Display(r.Latest), r.NewSpec(r.Latest)
		}
		if pr := bot.openFor(r.Dep); pr != nil {
			u.PRNumber = pr.Number
		} else if n := opened[r.Manifest+"\x00"+r.Name]; n > 0 {
			u.PRNumber = n
		}
		ups = append(ups, u)
	}
	if failed > 0 {
		problems = append(problems, fmt.Sprintf("%d of %d dependencies couldn't be looked up", failed, len(results)))
	}
	if err := a.db.ReplaceDepUpdates(ctx, repo.ID, ups); err != nil {
		return err
	}
	if len(problems) > 0 {
		return errors.New(strings.Join(problems, "; "))
	}
	return nil
}

func secPlanName(p depupdates.PR) string {
	if p.Group {
		return p.Title()
	}
	return p.Updates[0].Name
}

// secBotPulls are the updates bot's pull requests in a repository.
type secBotPulls struct {
	all     []store.Pull
	members map[int64]map[string]bool // open grouped PR -> manifest\x00name
}

func (a *App) secBotPRs(ctx context.Context, repoID int64) (*secBotPulls, error) {
	prs, err := a.db.PullsByAuthorPrefix(ctx, repoID, secBot.Kind, secBot.Name, secBotBranch)
	if err != nil {
		return nil, err
	}
	b := &secBotPulls{all: prs, members: map[int64]map[string]bool{}}
	for _, p := range prs {
		if !p.IsOpen() || !strings.Contains(p.Head, "/_group/") {
			continue
		}
		ms, err := a.db.DepUpdateMembers(ctx, repoID, p.Number)
		if err != nil {
			return nil, err
		}
		set := map[string]bool{}
		for _, m := range ms {
			set[m.Manifest+"\x00"+m.Name] = true
		}
		b.members[p.Number] = set
	}
	return b, nil
}

// openFor is the open pull request already updating a dependency: its own,
// for any version, or a grouped one that contains it.
func (b *secBotPulls) openFor(d depupdates.Dep) *store.Pull {
	pre := depupdates.BranchPrefix(d)
	for i, p := range b.all {
		if p.IsOpen() && strings.HasPrefix(p.Head, pre) {
			return &b.all[i]
		}
	}
	for i, p := range b.all {
		if p.IsOpen() && b.members[p.Number][d.Manifest+"\x00"+d.Name] {
			return &b.all[i]
		}
	}
	return nil
}

// find returns the open PR under prefix, or any PR from exactly branch.
func (b *secBotPulls) find(prefix, branch string) (open, same *store.Pull) {
	for i, p := range b.all {
		if p.IsOpen() && strings.HasPrefix(p.Head, prefix) && open == nil {
			open = &b.all[i]
		}
		if p.Head == branch && same == nil {
			same = &b.all[i]
		}
	}
	return open, same
}

// secOpenPlannedPR creates the branch, its commits and the pull request for
// one planned update, unless the bot already has one. A pull request closed
// without merging is never reopened for the same update (same branch); an
// open grouped pull request blocks a second one for the same folder until
// it is merged or closed. It returns the PR number (0 when none).
func (a *App) secOpenPlannedPR(ctx context.Context, repo store.Repo, g *gitrepo.Repo, base, tip string, p depupdates.PR,
	bot *secBotPulls, dset store.DepUpdateSettings) (int64, error) {
	open, same := bot.find(p.Prefix, p.Branch)
	switch {
	case p.Group && open != nil:
		return 0, nil // the open group PR stays until it's merged or closed
	case open != nil:
		return open.Number, nil
	case same != nil:
		return same.Number, nil // never a second PR for the same update, even if the first was closed
	}
	head, err := g.BranchSHA(ctx, p.Branch)
	if err != nil {
		sig := gitrepo.Signature{Name: secBotName, Email: secBotName + "@atelier.invalid", When: time.Now()}
		edits := map[string][]byte{}
		var order []string
		for _, r := range p.Updates {
			cur, ok := edits[r.Manifest]
			if !ok {
				blob, err := g.Blob(ctx, tip, r.Manifest, 1<<20)
				if err != nil || blob.TooLarge {
					return 0, fmt.Errorf("can't read %s", r.Manifest)
				}
				cur = blob.Data
				order = append(order, r.Manifest)
			}
			next, err := r.Edit(cur)
			if err != nil {
				return 0, err
			}
			edits[r.Manifest] = next
		}
		sort.Strings(order)
		parent := tip
		for _, m := range order {
			sha, err := g.CommitFile(ctx, gitrepo.FileCommit{Parent: parent, Path: m, Content: edits[m], Message: p.CommitMessage(m), Author: sig})
			if err != nil {
				return 0, err
			}
			parent = sha
		}
		if err := g.CreateBranch(ctx, p.Branch, parent, sig); err != nil && !errors.Is(err, gitrepo.ErrBranchExists) {
			return 0, err
		}
		if head, err = g.BranchSHA(ctx, p.Branch); err != nil {
			return 0, err
		}
		// Branches made here move refs without hooks: queue the push so
		// `on: push` workflows (CI, the lockfile job) run on the new branch.
		push := store.ActionsPush{Owner: repo.Owner, Repo: repo.Name, Old: strings.Repeat("0", 40), New: head,
			Ref: "refs/heads/" + p.Branch, Pusher: secBot.Kind + ":" + secBot.Name}
		st := a.actions()
		st.go_(func() { a.handlePush(context.WithoutCancel(ctx), push) })
	}
	pr, err := a.db.CreatePull(ctx, store.NewPull{RepoID: repo.ID, Title: p.Title(), Body: p.Body(depupdates.BodyOptions{Lockfiles: dset.Lockfiles}),
		Head: p.Branch, Base: base, HeadSHA: head, AuthorKind: secBot.Kind, AuthorName: secBot.Name})
	if err != nil {
		return 0, err
	}
	bot.all = append([]store.Pull{pr}, bot.all...)
	if p.Group {
		var ms []store.DepUpdateMember
		set := map[string]bool{}
		for _, r := range p.Updates {
			ms = append(ms, store.DepUpdateMember{PRNumber: pr.Number, Manifest: r.Manifest, Name: r.Name, Version: r.Display(r.Latest)})
			set[r.Manifest+"\x00"+r.Name] = true
		}
		if err := a.db.AddDepUpdateMembers(ctx, repo.ID, ms); err != nil {
			return pr.Number, err
		}
		bot.members[pr.Number] = set
	}
	a.emit(ctx, Event{Kind: EventPullOpened, Repo: repo, RepoID: repo.ID, Number: pr.Number, Title: pr.Title,
		URL: fmt.Sprintf("/%s/pulls/%d", repo.FullName(), pr.Number), Actor: secBot, Detail: eventExcerpt(pr.Body, 140)})
	return pr.Number, nil
}

// secDepsDue reports whether the scheduler should check now: a week after
// the last check, or on the repository's schedule day (once that day).
func secDepsDue(last, now time.Time, day int) bool {
	if day < 0 || day > 6 {
		return last.IsZero() || now.Sub(last) >= secDepsEvery
	}
	if int(now.Weekday()) != day {
		return false
	}
	y, m, d := now.Date()
	return last.Before(time.Date(y, m, d, 0, 0, 0, 0, now.Location()))
}

// secDepsScheduler checks each repository with a manifest about once a
// week, or on its schedule day.
func (a *App) secDepsScheduler(ctx context.Context) {
	timer := time.NewTimer(3 * time.Minute)
	defer timer.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-timer.C:
		}
		repos, err := a.db.Repos(ctx)
		if err == nil {
			for _, rp := range repos {
				if ctx.Err() != nil {
					return
				}
				var last time.Time
				if sc, err := a.db.SecurityScanState(ctx, rp.ID, "deps"); err == nil {
					last = sc.StartedAt
				}
				dset, err := a.db.DepUpdateSettings(ctx, rp.ID)
				if err != nil || !secDepsDue(last, time.Now(), dset.ScheduleDay) {
					continue
				}
				if !a.secHasManifest(ctx, rp) {
					continue
				}
				if ok, err := a.db.StartSecurityScan(ctx, rp.ID, "deps", secDepsTimeout+time.Minute); err == nil && ok {
					a.secFinishDepsCheck(ctx, rp) // one at a time
				}
			}
		}
		timer.Reset(time.Hour)
	}
}
