// Style is the chroma style the CSS was generated from.
func Style() *chroma.Style { return atelier }

// CSS is the stylesheet for highlighted code, committed as
// internal/web/static/highlight.css (go test ./internal/highlight -run CSS
// -update rewrites it). Rules are scoped by the hl- class prefix alone, so
// highlighted spans work in any code container.
func CSS() string {
	var buf bytes.Buffer
	f := formatterForCSS()
	_ = f.WriteCSS(&buf, atelier)
	var b strings.Builder
	b.WriteString("/* Syntax highlighting (hl- classes), generated by internal/highlight: do not edit by hand.\n")
	b.WriteString("   Regenerate with: go test ./internal/highlight -run TestCSSUpToDate -update */\n\n")
	b.WriteString(extraCSS)
	for _, line := range strings.Split(buf.String(), "\n") {
		// Drop the wrapper rules (.hl-bg, .hl-chroma): each page's code
		// container keeps its own background.
		sel, _, ok := strings.Cut(line, " {")
		if !ok || !strings.HasPrefix(sel, ".hl-chroma .hl-") {
			continue
		}
		switch strings.TrimPrefix(sel, ".hl-chroma .hl-") {
		case "lnlinks", "lntd", "lntable", "hl", "lnt", "ln", "line", "cl": // line-number layout we don't use
			continue
		}
		b.WriteString(strings.TrimPrefix(line, ".hl-chroma "))
		b.WriteByte('\n')
	}
	return b.String()
}

func formatterForCSS() *chtml.Formatter {
	return chtml.New(chtml.WithClasses(true), chtml.ClassPrefix("hl-"), chtml.WithCSSComments(false))
}

// extraCSS is the hand-written part: the note shown when a file is too big
// to colour, the language label, and Markdown blocks.
const extraCSS = `.hl-note { padding: 8px 16px; border-bottom: 1px solid var(--border); }
.hl-lang { color: var(--text-2); }

`
