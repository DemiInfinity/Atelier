package runner

import (
	"context"
	"encoding/base64"
	"fmt"
	"io/fs"
	"path/filepath"
	"strings"

	"atelier/internal/depupdates"
)

// atelier/update-lockfiles is built into the runner (like
// atelier/deploy-pages). On an atelier-updates/* branch it regenerates the
// lockfiles in the checkout (npm, pnpm, yarn, go.sum, Gradle lock and
// verification files; see depupdates.LockfileCommands), commits them as
// atelier-updates and pushes the commit to the branch with the job token.
// On any other branch it does nothing. The server only accepts the push
// when the repository allows lockfile regeneration, the bot has an open
// pull request from the branch, and the commit changes only lockfiles.
//
//	- uses: actions/checkout@v4
//	- uses: atelier/update-lockfiles@v1
//	  with:
//	    path: .        # the checkout (default: the workspace)
//
// Output: pushed ("true" or "false").

const updateLockfilesAction = "atelier/update-lockfiles"

func isUpdateLockfiles(u string) bool {
	spec, _, _ := strings.Cut(strings.ToLower(strings.TrimSpace(u)), "@")
	return spec == updateLockfilesAction
}

// lockfileBranch is the branch the job may push lockfiles to, or "" (with
// the reason) when the step should do nothing.
func lockfileBranch(ref string) (string, string) {
	branch, ok := strings.CutPrefix(ref, "refs/heads/")
	if !ok || !depupdates.IsUpdateBranch(branch) {
		return "", fmt.Sprintf("Skipping: %s isn't an atelier-updates/* branch.", orDefault(ref, "this run"))
	}
	return branch, ""
}

func (j *jobRun) updateLockfiles(ctx context.Context, sc *scope, stepEnv envMap, fc *fileCmds, with map[string]string) (map[string]string, int, error) {
	step := sc.logStep
	out := map[string]string{"pushed": "false"}
	branch, why := lockfileBranch(j.job.Ref)
	if branch == "" {
		j.log.System(step, why)
		return out, 0, nil
	}
	dir := j.ws
	if p := strings.TrimSpace(with["path"]); p != "" && p != "." {
		dir = filepath.Join(j.ws, filepath.FromSlash(p))
		if rel, err := filepath.Rel(j.ws, dir); err != nil || strings.HasPrefix(rel, "..") {
			return nil, 1, fmt.Errorf("update-lockfiles path %q is outside the workspace", p)
		}
	}
	if j.job.JobToken == "" {
		return nil, 1, fmt.Errorf("update-lockfiles needs a job token")
	}
	var files []string
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		rel, _ := filepath.Rel(dir, p)
		if d.IsDir() && rel != "." && depupdates.SkipDir(d.Name()) {
			return filepath.SkipDir
		}
		if !d.IsDir() {
			files = append(files, filepath.ToSlash(rel))
		}
		return nil
	})
	if err != nil {
		return nil, 1, err
	}
	cmds := depupdates.LockfileCommands(files)
	if len(cmds) == 0 {
		j.log.System(step, "No lockfiles to regenerate.")
		return out, 0, nil
	}
	// The step's own environment: PATH with GITHUB_PATH additions (setup-node,
	// setup-go, setup-java), job and step env. Always on the host.
	env := j.processEnv(sc, stepEnv, fc, hostPaths, false, "")
	env.Set("GIT_TERMINAL_PROMPT", "0")
	for _, c := range cmds {
		j.log.System(step, fmt.Sprintf("%s: %s (for %s)", orDefault(c.Dir, "."), strings.Join(c.Argv, " "), c.Why))
		code, err := j.run(ctx, step, c.Argv, "", filepath.Join(dir, filepath.FromSlash(c.Dir)), env, newCmdState())
		if err != nil || code != 0 {
			return out, failCode(code), fmt.Errorf("%s failed in %s: %v", strings.Join(c.Argv, " "), orDefault(c.Dir, "."), err)
		}
	}

	// Stage lockfiles only: anything else the tools touched stays behind.
	git := func(args ...string) (int, error) {
		return j.run(ctx, step, append([]string{"git", "-C", dir}, args...), "", dir, env, newCmdState())
	}
	var lockfiles []string
	_ = filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		rel, _ := filepath.Rel(dir, p)
		if d.IsDir() && rel != "." && depupdates.SkipDir(d.Name()) {
			return filepath.SkipDir
		}
		if !d.IsDir() && depupdates.IsLockfile(filepath.ToSlash(rel)) {
			lockfiles = append(lockfiles, filepath.ToSlash(rel))
		}
		return nil
	})
	if len(lockfiles) == 0 {
		j.log.System(step, "No lockfiles were written.")
		return out, 0, nil
	}
	if code, err := git(append([]string{"add", "--"}, lockfiles...)...); code != 0 || err != nil {
		return out, failCode(code), err
	}
	if code, _ := git("diff", "--cached", "--quiet"); code == 0 {
		j.log.System(step, "Lockfiles are already up to date.")
		return out, 0, nil
	}
	commit := []string{"-c", "user.name=atelier-updates", "-c", "user.email=atelier-updates@atelier.invalid",
		"commit", "-q", "-m", "Update lockfiles", "-m", "Regenerated by atelier/update-lockfiles."}
	if code, err := git(commit...); code != 0 || err != nil {
		return out, failCode(code), err
	}
	auth := base64.StdEncoding.EncodeToString([]byte("atelier:" + j.job.JobToken))
	j.mask.Add(auth)
	pushEnv := env.Clone()
	pushEnv.Set("GIT_CONFIG_COUNT", "1")
	pushEnv.Set("GIT_CONFIG_KEY_0", "http."+urlOrigin(j.job.CloneURL)+"/.extraheader")
	pushEnv.Set("GIT_CONFIG_VALUE_0", "AUTHORIZATION: basic "+auth)
	push := []string{"git", "-C", dir, "push", j.job.CloneURL, "HEAD:refs/heads/" + branch}
	if code, err := j.run(ctx, step, push, "", dir, pushEnv, newCmdState()); code != 0 || err != nil {
		return out, failCode(code), fmt.Errorf("pushing lockfiles to %s was refused (is \"Regenerate lockfiles\" on in the Security settings?)", branch)
	}
	j.log.System(step, "Pushed updated lockfiles to "+branch)
	out["pushed"] = "true"
	return out, 0, nil
}
